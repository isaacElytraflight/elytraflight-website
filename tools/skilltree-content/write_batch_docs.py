#!/usr/bin/env python3
"""Write the per-batch changelog, brief, report, and version list.

Inputs are docs/batches/<id>.json, the skill graph, the bank and explainer
files, and docs/gates/<id>.json from run_gates.py. The markdown is generated.
Do not edit those four outputs by hand.

  python3 tools/skilltree-content/write_batch_docs.py --batch me132-b1
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def load_json(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def words(sections):
    text = "\n".join(s.get("body_md") or "" for s in sections)
    text = re.sub(r"\\\([\s\S]*?\\\)|\\\[[\s\S]*?\\\]", " ", text)
    text = re.sub(r"[#*_`>|]", " ", text)
    return len(text.split())


def skill_boxes(collections, sid):
    by_id = {b["id"]: b for b in collections["boxes"]}
    child_ids = {c for b in collections["boxes"] for c in (b.get("children") or [])}
    tops = [b for b in collections["boxes"] if b["id"] not in child_ids]

    def members(box):
        out = set(box.get("skills") or [])
        for child in box.get("children") or []:
            out |= members(by_id[child])
        return out

    return [top["id"] for top in tops if sid in members(top)]


def batch_items(spec, skills):
    by_id = {s["id"]: s for s in skills["skills"]}
    items = []
    counts = []
    for sid in spec["skills"]:
        bank = load_json(os.path.join(ROOT, "skilltree", "bank", sid + ".json"))
        expl = load_json(os.path.join(ROOT, "skilltree", "explainers", sid + ".json"))
        qs = bank["questions"]
        n_mc = sum(1 for q in qs if q.get("type") == "mc")
        n_fig = sum(1 for q in qs if q.get("figure"))
        for q in qs:
            items.append({"id": q["id"], "version": int(q.get("version") or 1)})
        items.append({"id": sid + "#explainer", "version": int(expl.get("version") or 1)})
        counts.append({
            "id": sid,
            "prereqs": by_id[sid].get("prereqs") or [],
            "questions": len(qs),
            "mc": n_mc,
            "numeric": len(qs) - n_mc,
            "figures": n_fig,
            "words": words(expl.get("sections") or []),
            "explainer_version": int(expl.get("version") or 1),
        })
    return items, counts


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def changelog(batches):
    lines = [
        "# Content changelog",
        "",
        "Generated by `tools/skilltree-content/write_batch_docs.py`. Do not edit by hand.",
        "Ids do not change. A content edit bumps that item's version. `docs/content-versions.json` stores `(id, version)`.",
        "",
    ]
    for spec, items, counts in batches:
        lines.append(f"## {spec['label']} — {spec['id']}")
        lines.append("")
        lines.append(f"Box: {spec['box']}.")
        lines.append("")
        lines.append("Skills: " + ", ".join(f"`{c['id']}`" for c in counts) + ".")
        lines.append("")
        bumped = [it for it in items if it["version"] > 1]
        if bumped:
            lines.append("Items above version 1:")
            lines.append("")
            for it in bumped:
                lines.append(f"- `{it['id']}` version {it['version']}")
            lines.append("")
        else:
            lines.append("Every item is version 1.")
            lines.append("")
        lines.append("The shingle gate and the manual spot audit are deferred. They are not part of this batch.")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def brief(spec, counts, boxes):
    lines = [
        f"# Brief: {spec['label']}",
        "",
        "Generated by `tools/skilltree-content/write_batch_docs.py`. Do not edit by hand.",
        "",
        "Do not publish.",
        "",
        "## Box, layer, reserved ids",
        "",
        f"- Box: {spec['box']}.",
        f"- Layer: {spec['label']}. Plan: `{spec['plan']}`.",
        "- Reserved ids: " + ", ".join(f"`{c['id']}`" for c in counts) + ".",
        "",
        "## Prerequisites, registries, sources",
        "",
        "| id | prerequisites | boxes | registry areas |",
        "|---|---|---|---|",
    ]
    for c in counts:
        pres = ", ".join(f"`{p}`" for p in c["prereqs"]) or "none"
        box = ", ".join(f"`{b}`" for b in boxes[c["id"]]) or "none"
        areas = ", ".join(spec.get("areas", {}).get(c["id"], [])) or "see the notation registry"
        lines.append(f"| `{c['id']}` | {pres} | {box} | {areas} |")
    cores = spec.get("cores") or []
    lines += [
        "",
        f"Read `{spec['notation']}` before writing. Read `{spec['sources']}` for licenses and sections.",
        "Read `docs/batch-starter.md` for the read order, helpers, gates, and efficiency rules.",
        "No source or textbook name in learner-facing content: stems, choices, explanations, explainers, figures, alt text, or the skill panel.",
        "",
        "## Bank, explainer, core or application",
        "",
        "- 4 rounds × 3 auto-graded questions. Round 1 practice. Rounds 2–3 mastery. Round 4 application, with a preview link to a descendant.",
        "- Multiple choice: 4 options, balanced positions, real-mistake distractors. Numeric: nonzero answer, a unit, relative tolerance 0.02.",
        "- Deep types, written with `Bank.sym`, `Bank.order`, `Bank.find_error`, and `Bank.multi` in `tools/skilltree-content/banklib.py`: symbolic expressions (declared variables, random-point grading, `alternates` for equivalent forms), step ordering, find-the-error, and multi-select. Each is simply correct or incorrect.",
        "- Deep-type quota: at least 3 of those four types per 12 questions, `ceil(3n/12)` for another length (`deep_quota` in `banklib.py`). The domain gate enforces it. Banks in `skilltree/deep_quota_grandfather.json` are exempt. Do not add ids to that list.",
        "- Explanations work the answer and say why the tempting wrong answers fail. No option letters. No `$` math.",
        "- Figures from `tools/skilltree-content/templates.py` where the shape is one of the shared templates. Alt text does not reveal the answer.",
        "- Explainer: idea, key equations, worked example, pitfalls, where this leads. 250–500 words, at least one figure. The worked example uses none of that skill's quiz numbers.",
    ]
    if cores:
        lines.append("- Cores: " + ", ".join(f"`{c}`" for c in cores) + ". The other skills in this batch are applications.")
    lines += [
        "",
        "## Gates",
        "",
        f"`python3 tools/skilltree-content/run_gates.py --batch {spec['id']}`.",
        "That runs the schema, graph, and domain validators, the batch numeric verifier, the figure-bounds check, strict KaTeX, and the content, merge, migrate, and Puppeteer tests.",
        "The shingle gate and the 10% spot audit are deferred. Writers paraphrase from understanding: no copied wording, problems, parameter sets, or figures.",
        "",
        "## Deliverables",
        "",
        "Content, generator, verifier, this brief, the report, and `docs/content-versions.json`. Do not publish.",
        "",
    ]
    return "\n".join(lines)


def report(spec, counts, items, gate):
    n_q = sum(c["questions"] for c in counts)
    n_mc = sum(c["mc"] for c in counts)
    n_fig = sum(c["figures"] for c in counts)
    lines = [
        f"# Report: {spec['label']}",
        "",
        "Generated by `tools/skilltree-content/write_batch_docs.py`. Do not edit by hand.",
        "",
        "Do not publish.",
        "",
        "## Counts",
        "",
        f"- {len(counts)} skills, {n_q} questions ({n_mc} multiple choice, {n_q - n_mc} numeric), {len(counts)} explainers.",
        f"- {n_fig} question figures.",
        "- Explainer words: " + ", ".join(f"`{c['id']}` {c['words']}" for c in counts) + ".",
        "",
        "## Versions",
        "",
    ]
    bumped = [it for it in items if it["version"] > 1]
    if bumped:
        lines.append("Items above version 1:")
        lines.append("")
        for it in bumped:
            lines.append(f"- `{it['id']}` version {it['version']}")
        lines.append("")
    else:
        lines.append("Every item is version 1.")
        lines.append("")
    lines.append(f"The full list is `docs/content-versions.json`.")
    lines.append("")
    lines.append("## Gates")
    lines.append("")
    if not gate:
        lines.append("No gate summary yet. Run `tools/skilltree-content/run_gates.py`.")
    else:
        for step in gate["steps"]:
            mark = "PASS" if step["ok"] else "FAIL"
            lines.append(f"- {mark} `{step['name']}`: {step['summary']}")
        lines.append("")
        lines.append("Overall: " + ("pass" if gate.get("ok") else "fail") + ".")
    lines += [
        "",
        "## Copyright",
        "",
        "Writers paraphrase from understanding. No copied wording, problems, parameter sets, or figures, and no source names in learner-facing content.",
        "The automated shingle gate and the manual spot audit are deferred to a later cleanup pass.",
        "",
        "## Dedupe",
        "",
        f"See `{spec['plan']}`.",
        "",
    ]
    return "\n".join(lines)


def main():
    args = sys.argv[1:]
    only = None
    if "--batch" in args:
        only = args[args.index("--batch") + 1]
    paths = sorted(glob.glob(os.path.join(ROOT, "docs", "batches", "*.json")))
    if only:
        paths = [p for p in paths if os.path.splitext(os.path.basename(p))[0] == only]
    skills = load_json(os.path.join(ROOT, "skilltree", "ee105_skills_draft.json"))
    collections = load_json(os.path.join(ROOT, "skilltree", "collections.json"))
    batches = []
    all_items = []
    for path in paths:
        spec = load_json(path)
        items, counts = batch_items(spec, skills)
        boxes = {c["id"]: skill_boxes(collections, c["id"]) for c in counts}
        gate_path = os.path.join(ROOT, "docs", "gates", spec["id"] + ".json")
        gate = load_json(gate_path) if os.path.exists(gate_path) else None
        batches.append((spec, items, counts))
        all_items.extend(items)
        write(os.path.join(ROOT, "docs", "briefs", spec["id"] + ".md"), brief(spec, counts, boxes))
        write(os.path.join(ROOT, "docs", "reports", spec["id"] + ".md"), report(spec, counts, items, gate))
        print("wrote", spec["id"])
    # Versions cover every batch file. A one-batch run must not drop the others.
    version_items = all_items
    if only:
        version_items = []
        for path in sorted(glob.glob(os.path.join(ROOT, "docs", "batches", "*.json"))):
            spec = load_json(path)
            items, _counts = batch_items(spec, skills)
            version_items.extend(items)
    versions = {
        "batch": "all",
        "note": "Generated from the bank and explainer files. Learner progress is separate.",
        "items": version_items,
    }
    write(os.path.join(ROOT, "docs", "content-versions.json"), json.dumps(versions, indent=2) + "\n")
    # Changelog covers every batch file, even when this run was asked for one.
    if only:
        full = []
        for path in sorted(glob.glob(os.path.join(ROOT, "docs", "batches", "*.json"))):
            spec = load_json(path)
            items, counts = batch_items(spec, skills)
            full.append((spec, items, counts))
        write(os.path.join(ROOT, "docs", "CHANGELOG.md"), changelog(full))
    else:
        write(os.path.join(ROOT, "docs", "CHANGELOG.md"), changelog(batches))


if __name__ == "__main__":
    main()
